    mobile_hash VARCHAR(255),

    vehicle_customer_key BIGINT
        REFERENCES dim_vehicle_customer(vehicle_customer_key),

    center_id VARCHAR(50)
        REFERENCES dim_service_center(center_id),

    city VARCHAR(100)
