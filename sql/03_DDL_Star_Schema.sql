-- VIEW: vw_vehicle_identifier_map
BEGIN;

CREATE OR REPLACE VIEW vw_vehicle_identifier_map AS
WITH registration_bridge AS (
    SELECT vehicle_reg_no, MIN(chassis_no) AS chassis_no
    FROM public.master_id_map WHERE vehicle_reg_no IS NOT NULL GROUP BY vehicle_reg_no
), identified AS (
    SELECT m.customer_id, m.vehicle_reg_no, m.chassis_no, m.mobile_hash,
            CASE WHEN COALESCE(m.chassis_no, b.chassis_no) IS NOT NULL THEN 'CHASSIS'
                WHEN m.vehicle_reg_no IS NOT NULL THEN 'REGISTRATION'
                WHEN m.customer_id IS NOT NULL THEN 'CUSTOMER_ONLY' ELSE 'MOBILE_ONLY' END AS
                    identity_type,
            COALESCE(m.chassis_no, b.chassis_no, m.vehicle_reg_no, m.customer_id, m.mobile_hash) AS
                identity_value
    FROM public.master_id_map m LEFT JOIN registration_bridge b USING (vehicle_reg_no)
)
SELECT m.customer_id, m.vehicle_reg_no, m.chassis_no, m.mobile_hash, v.vehicle_customer_key
FROM identified m LEFT JOIN dim_vehicle_customer v USING (identity_type, identity_value);

COMMIT;

-- VIEW: vw_city_service_gap
BEGIN;

CREATE OR REPLACE VIEW vw_city_service_gap AS
WITH months AS (
    SELECT DISTINCT make_date(year, month, 1) AS month_start FROM dim_date WHERE year IN (2023,
        2024)
), sales AS (
    SELECT date_trunc('month', sale_date)::date AS month_start, city, SUM(units_sold) AS units
    FROM fact_sales GROUP BY 1, 2
), complaints AS (
    SELECT date_trunc('month', complaint_date)::date AS month_start, city, COUNT(*) AS tickets
    FROM fact_complaints WHERE complaint_date IS NOT NULL GROUP BY 1, 2
), grid AS (
    SELECT m.month_start, c.city_name AS city, COALESCE(s.units, 0) AS monthly_sales,
            COALESCE(t.tickets, 0) AS monthly_complaints
    FROM months m CROSS JOIN dim_city c
    LEFT JOIN sales s ON s.month_start = m.month_start AND s.city = c.city_name
    LEFT JOIN complaints t ON t.month_start = m.month_start AND t.city = c.city_name
), fleet AS (
    SELECT *, SUM(monthly_sales) OVER (PARTITION BY city ORDER BY month_start ROWS UNBOUNDED
        PRECEDING) AS cumulative_vehicles
    FROM grid
), capacity AS (
    SELECT m.month_start, c.city, COUNT(*) AS active_centers,
            SUM(c.capacity_jobs_per_day) AS capacity_jobs_per_day
    FROM months m JOIN dim_service_center c
        ON c.opened_date < m.month_start + INTERVAL '1 month' AND NOT c.source_record_missing
    GROUP BY m.month_start, c.city
)
SELECT f.*, COALESCE(c.active_centers, 0) AS active_centers, c.capacity_jobs_per_day,
        ROUND(f.cumulative_vehicles / NULLIF(c.active_centers, 0), 2) AS vehicles_per_center,
        ROUND(f.monthly_complaints * 1000.0 / NULLIF(f.cumulative_vehicles, 0), 2) AS
            complaints_per_1000_vehicles
FROM fleet f LEFT JOIN capacity c USING (month_start, city);

COMMIT;

-- VIEW: vw_monthly_kpis
BEGIN;

CREATE OR REPLACE VIEW vw_monthly_kpis AS
WITH fleet AS (
    SELECT month_start, SUM(monthly_sales) AS monthly_sales, SUM(cumulative_vehicles) AS
        cumulative_vehicles,
            SUM(active_centers) AS active_centers FROM vw_city_service_gap GROUP BY month_start
), complaints AS (
    SELECT date_trunc('month', complaint_date)::date AS month_start, COUNT(*) AS total_complaints,
            AVG(tat_days) AS avg_tat_days, COUNT(tat_days) AS known_tat_tickets,
            AVG(csat_score) FILTER (WHERE UPPER(TRIM(status)) IN ('RESOLVED', 'CLOSED')) AS
                avg_csat_score,
            COUNT(csat_score) FILTER (WHERE UPPER(TRIM(status)) IN ('RESOLVED', 'CLOSED')) AS
                csat_rated_resolved_tickets,
            COUNT(*) FILTER (WHERE UPPER(TRIM(status)) = 'ESCALATED') AS escalated_tickets
    FROM fact_complaints WHERE complaint_date IS NOT NULL GROUP BY 1
), registrations AS (
    SELECT date_trunc('month', reg_date)::date AS month_start, SUM(registrations) AS
        total_registrations,
            SUM(registrations) FILTER (WHERE LOWER(TRIM(oem)) = 'ola electric') AS ola_registrations
    FROM fact_vahan_registrations GROUP BY 1
), spares AS (
    SELECT date_trunc('month', week_start)::date AS month_start,
            CASE WHEN COUNT(stockout_days) = COUNT(*) THEN
                COUNT(*) FILTER (WHERE stockout_days > 0) * 100.0 / NULLIF(COUNT(*), 0) END AS
                    stockout_rate_pct
    FROM fact_spare_parts GROUP BY 1
), social AS (
    SELECT date_trunc('month', feedback_date)::date AS month_start, COUNT(*) AS dated_social_posts,
            CASE WHEN COUNT(sentiment_label) = COUNT(*) THEN
                (COUNT(*) FILTER (WHERE sentiment_label = 'Positive') - COUNT(*) FILTER (WHERE
                    sentiment_label = 'Negative'))::numeric
                / NULLIF(COUNT(*), 0) END AS sentiment_index
    FROM fact_sentiment WHERE source = 'Social Media' AND feedback_date IS NOT NULL GROUP BY 1
), jobs AS (
    SELECT date_trunc('month', open_date)::date AS month_start,
            COUNT(*) FILTER (WHERE UPPER(TRIM(status)) = 'AWAITING_PARTS') * 100.0 /
                NULLIF(COUNT(*), 0) AS awaiting_parts_pct
    FROM fact_jobcards GROUP BY 1
)
SELECT EXTRACT(YEAR FROM f.month_start)::int AS year, EXTRACT(MONTH FROM f.month_start)::int AS
    month,
        f.month_start, f.monthly_sales, f.cumulative_vehicles, f.active_centers,
        COALESCE(c.total_complaints, 0) AS total_complaints,
        ROUND(c.avg_tat_days, 2) AS avg_tat_days, c.known_tat_tickets,
        ROUND(c.avg_csat_score, 2) AS avg_csat_score, c.csat_rated_resolved_tickets,
        ROUND(COALESCE(c.total_complaints, 0)*1000.0 / NULLIF(f.cumulative_vehicles, 0), 2) AS
            complaints_per_1000_vehicles,
        ROUND(f.cumulative_vehicles / NULLIF(f.active_centers, 0), 2) AS vehicles_per_center,
        ROUND(c.escalated_tickets*100.0 / NULLIF(c.total_complaints, 0), 2) AS escalation_rate_pct,
        ROUND(r.ola_registrations*100.0 / NULLIF(r.total_registrations, 0), 2) AS
            ola_market_share_pct,
        ROUND(s.stockout_rate_pct, 2) AS stockout_rate_pct,
        so.dated_social_posts, ROUND(so.sentiment_index, 4) AS sentiment_index,
        ROUND(j.awaiting_parts_pct, 2) AS awaiting_parts_pct
FROM fleet f LEFT JOIN complaints c USING(month_start) LEFT JOIN registrations r USING(month_start)
LEFT JOIN spares s USING(month_start) LEFT JOIN social so USING(month_start) LEFT JOIN jobs j
    USING(month_start);

COMMIT;

-- VIEW: vw_cross_validation_discrepancies
BEGIN;

CREATE OR REPLACE VIEW vw_cross_validation_discrepancies AS
SELECT c.ticket_id, c.status AS complaint_status, j.jobcard_id, j.status AS jobcard_status
FROM fact_complaints c JOIN fact_jobcards j ON j.linked_ticket_key = c.ticket_id
WHERE UPPER(TRIM(c.status)) IN ('RESOLVED', 'CLOSED')
    AND UPPER(TRIM(j.status)) IN ('OPEN', 'AWAITING_PARTS');

COMMIT;

-- VIEW: public.vw_legacy_sales_conflicts
BEGIN;

CREATE OR REPLACE VIEW public.vw_legacy_sales_conflicts AS
SELECT
    l.sale_date,
    l.city,
    l.model,
    l.units_sold AS legacy_units_sold,
    n.units_sold AS new_units_sold,
    n.units_sold - l.units_sold AS units_difference,
    'New system wins'::TEXT AS resolution_rule
FROM public.raw_archived_sales_legacy l
JOIN public.raw_ola_sales_daily_2023 n
    ON l.sale_date = n.sale_date
    AND l.city = n.city
    AND l.model = n.model
WHERE l.units_sold IS DISTINCT FROM n.units_sold;

COMMIT;
