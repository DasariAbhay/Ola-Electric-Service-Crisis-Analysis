    ticket_id VARCHAR(50) PRIMARY KEY,
    complaint_date DATE REFERENCES dim_date(date_key),
    complaint_date_inferred DATE REFERENCES dim_date(date_key),
    resolution_date DATE REFERENCES dim_date(date_key),
    customer_id VARCHAR(100),
    vehicle_reg_no VARCHAR(100),
    vehicle_customer_key BIGINT REFERENCES dim_vehicle_customer(vehicle_customer_key),
